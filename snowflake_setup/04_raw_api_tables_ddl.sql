-- Create Tables in Snowflake
-- These steps were reverse-engineered, as the actual loading of data was done using Snowflake's UI and Load Wizard

create or replace TABLE API_SETS (
	SET_NUM VARCHAR(16777216),
	NAME VARCHAR(16777216),
	YEAR NUMBER(38,0),
	THEME_ID NUMBER(38,0),
	NUM_PARTS NUMBER(38,0)
);


create or replace TABLE API_INVENTORY_PARTS (
	SET_NUM VARCHAR(16777216),
	PART_NUM VARCHAR(16777216),
	COLOR_ID NUMBER(38,0),
	QUANTITY NUMBER(38,0),
	IS_SPARE BOOLEAN
);

create or replace TABLE API_MISSING_COLORS (
	ID NUMBER(38,0),
	NAME VARCHAR(16777216),
	RGB VARCHAR(16777216),
	IS_TRANS BOOLEAN
);

create or replace TABLE API_MISSING_PARTS (
	PART_NUM VARCHAR(16777216),
	NAME VARCHAR(16777216),
	PART_CAT_ID NUMBER(38,0)
);