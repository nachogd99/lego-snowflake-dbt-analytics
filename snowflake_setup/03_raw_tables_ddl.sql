-- These steps were reverse-engineered, as the actual loading of data was done using Snowflake's UI and Load Wizard

create or replace TABLE COLORS (
	ID NUMBER(38,0),
	NAME VARCHAR(16777216),
	RGB VARCHAR(16777216),
	IS_TRANS BOOLEAN
);

create or replace TABLE INVENTORIES (
	ID NUMBER(38,0),
	VERSION NUMBER(38,0),
	SET_NUM VARCHAR(16777216)
);

create or replace TABLE INVENTORY_PARTS (
	INVENTORY_ID NUMBER(38,0),
	PART_NUM VARCHAR(16777216),
	COLOR_ID NUMBER(38,0),
	QUANTITY NUMBER(38,0),
	IS_SPARE BOOLEAN
);

create or replace TABLE INVENTORY_SETS (
	INVENTORY_ID NUMBER(38,0),
	SET_NUM VARCHAR(16777216),
	QUANTITY NUMBER(38,0)
);

create or replace TABLE PART_CATEGORIES (
	ID NUMBER(38,0),
	NAME VARCHAR(16777216)
);

create or replace TABLE PARTS (
	PART_NUM VARCHAR(16777216),
	NAME VARCHAR(16777216),
	PART_CAT_ID NUMBER(38,0)
);

create or replace TABLE SETS (
	SET_NUM VARCHAR(16777216),
	NAME VARCHAR(16777216),
	YEAR NUMBER(38,0),
	THEME_ID NUMBER(38,0),
	NUM_PARTS NUMBER(38,0)
);

create or replace TABLE THEMES (
	ID NUMBER(38,0),
	NAME VARCHAR(16777216),
	PARENT_ID NUMBER(38,0)
);
